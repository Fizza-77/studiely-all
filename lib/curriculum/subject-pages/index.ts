export function getSubjectLandingByPath(
  path: string,
): SubjectLandingContent | undefined {
  const normalised = path.replace(/\/$/, "") || "/";
  return SUBJECT_LANDING_PAGES.find((page) => page.path === normalised);
}

export function resolveSubjectPageHref(input: {
  curriculum: string;
  pathway: string;
  year: string;
  subject: string;
}): string | null {
  const match = SUBJECT_PAGE_MATCHES.find(
    (item) =>
      item.curriculum === input.curriculum &&
      item.pathway === input.pathway &&
      item.years.includes(input.year) &&
      item.subject === input.subject,
  );
  return match?.path ?? null;
}
